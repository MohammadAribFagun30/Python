# List is mutable means it will change,
# if we change anything in the original List

# List of integers
list = [1,2,3,4,5]
print(list)

# List of different data type
List2 = ["Arib",30,"Alif",69]
print(List2)

List2[0] = "Fagun" # over write "Arib" to "Fagun"
print(List2)


